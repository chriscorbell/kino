#!/usr/bin/env node
// Writes the TV's string resources for the text both clients show, from the table in
// apps/desktop/src/locales/tv.ts. scripts/build-android.py runs it before Gradle.
//
//   node scripts/generate-tv-strings.mjs [destination]
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { tvStrings } from '../apps/desktop/src/locales/tv.ts';

const destination =
  process.argv[2] ??
  join(import.meta.dirname, '../build/android-strings/res/values/strings_shared.xml');

const argument = (index) => `\u0001${index}\u0001`;

function resource(name, entry) {
  const [message, ...formats] = typeof entry === 'object' ? entry : [entry];
  if (typeof message === 'string' && formats.length === 0) return escape(message, false);
  if (typeof message !== 'function' || message.length !== formats.length)
    throw new Error(`${name} needs one format type per message parameter`);
  const text = message(...formats.map((_, i) => argument(i + 1)));
  formats.forEach((_, i) => {
    // A message that branches on its argument cannot be one Android format string.
    if (!text.includes(argument(i + 1))) throw new Error(`${name} drops parameter ${i + 1}`);
  });
  return escape(text, true).replace(/\u0001(\d+)\u0001/g, (_, i) => `%${i}$${formats[i - 1]}`);
}

// Android's resource compiler trims and collapses unquoted whitespace and reads a leading @ or ?
// as a reference; a format string also reads % as a conversion.
function escape(text, formatted) {
  if (/^\s|\s$|[ \t]{2}/.test(text))
    throw new Error(`Unsupported whitespace in ${JSON.stringify(text)}`);
  return (formatted ? text.replace(/%/g, '%%') : text)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/"/g, '\\"')
    .replace(/\n/g, '\\n')
    .replace(/^[@?]/, '\\$&');
}

const rows = Object.entries(tvStrings).map(
  ([name, entry]) => `    <string name="${name}">${resource(name, entry)}</string>`,
);
mkdirSync(dirname(destination), { recursive: true });
writeFileSync(
  destination,
  `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate-tv-strings.mjs from apps/desktop/src/locales/tv.ts. Edit the text in en-US.ts. -->
<resources>
${rows.join('\n')}
</resources>
`,
);
