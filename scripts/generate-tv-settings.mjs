#!/usr/bin/env node
// Writes the TV's KinoSettings.kt from the settings schema in packages/settings. TV code reads and
// writes a Kino setting through the typed entry this file gives it, so a setting the schema does
// not list for the TV has no entry to read.
//
// With --check it writes nothing, and fails when the committed file differs from what the schema
// gives, or when a TV source reads, writes or removes one of those preferences by its raw key,
// which would get around the entry's type and default. The scan sees a key written as a string
// literal in the call, not one held in a variable.
//
//   node scripts/generate-tv-settings.mjs [--check]
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { settingsSchema } from '../packages/settings/src/schema.ts';

const root = join(import.meta.dirname, '..');
const sources = 'apps/android-tv/app/src/main/java';
const target = `${sources}/app/kino/tv/KinoSettings.kt`;

const pascal = (text) => text.replace(/(?:^|[_-])([a-z0-9])/gi, (_, first) => first.toUpperCase());

const tvSettings = Object.entries(settingsSchema).flatMap(([name, { value, platforms }]) =>
  platforms.tv ? [{ name, key: platforms.tv.key, value: platforms.tv.value ?? value }] : [],
);

const enums = [];
function entry({ name, key, value }) {
  const declare = (setting) => `    val ${name} = ${setting}`;
  if (value.kind === 'boolean') return declare(`BooleanSetting("${key}", ${value.default})`);
  if (value.kind === 'choice' && value.values.every((choice) => typeof choice === 'string')) {
    const type = pascal(name);
    const constant = (choice) => {
      if (!/^[a-z][a-z0-9_-]*$/i.test(choice))
        throw new Error(`${name}: "${choice}" cannot name a Kotlin enum constant`);
      return pascal(choice);
    };
    enums.push(
      `internal enum class ${type}(override val stored: String) : StoredChoice {\n` +
        value.values.map((choice) => `    ${constant(choice)}("${choice}"),\n`).join('') +
        '}\n',
    );
    return declare(
      `TextChoiceSetting("${key}", ${type}.${constant(value.default)}, ${type}.entries)`,
    );
  }
  if (value.kind === 'choice' && value.values.every(Number.isSafeInteger))
    return declare(
      `NumberChoiceSetting("${key}", ${value.default}, listOf(${value.values.join(', ')}))`,
    );
  throw new Error(`${name}: the TV has no storage for this ${value.kind}`);
}

const entries = tvSettings.map(entry);
const source = `// Generated by scripts/generate-tv-settings.mjs from packages/settings/src/schema.ts. Do not edit:
// change the schema and run pnpm android:settings.
package app.kino.tv

/** The Kino settings the TV honors. A setting the schema does not list for the TV has no entry. */
internal object KinoSettings {
${entries.join('\n')}
}
${enums.map((declaration) => `\n${declaration}`).join('')}`;

if (!process.argv.includes('--check')) {
  writeFileSync(join(root, target), source);
  console.log(`Wrote ${target}.`);
  process.exit(0);
}

const problems = [];
const committed = existsSync(join(root, target)) && readFileSync(join(root, target), 'utf8');
if (committed !== source)
  problems.push(
    `${target} does not match packages/settings/src/schema.ts. Run pnpm android:settings and commit the result.`,
  );

const settingFor = new Map(tvSettings.map((setting) => [setting.key, setting.name]));
const rawKey = /\b(?:(?:get|put)(?:Boolean|String|StringSet|Int|Long|Float)|remove)\(\s*"([^"]+)"/g;
for (const file of readdirSync(join(root, sources), { recursive: true })) {
  const path = `${sources}/${file}`;
  if (!path.endsWith('.kt') || path === target) continue;
  const text = readFileSync(join(root, path), 'utf8');
  for (const match of text.matchAll(rawKey)) {
    const name = settingFor.get(match[1]);
    if (!name) continue;
    const line = text.slice(0, match.index).split('\n').length;
    problems.push(
      `${path}:${line} names the "${match[1]}" preference by its raw key. Read it as settings[KinoSettings.${name}] and write it with put(KinoSettings.${name}, value).`,
    );
  }
}

for (const problem of problems) console.error(problem);
if (problems.length) process.exit(1);
console.log(
  `KinoSettings.kt matches the settings schema, and no TV source names its ${tvSettings.length} preferences by raw key.`,
);
